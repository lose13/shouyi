"""Run two original rule texts through one frozen Shouyi backend.

No expected answers, background card, or prior outputs enter model context.
The only varying model input between arms is the original rule text and the
memory generated by that arm. Original app sources and rules stay untouched.
"""
import argparse
import getpass
import hashlib
import json
import os
from pathlib import Path
import sys
from datetime import datetime, timedelta, timezone


ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "frozen-source"))
import engine
import model


def timestamp():
    return datetime.now(timezone(timedelta(hours=8))).isoformat()


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def atomic_json(path, value):
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")
    os.replace(temporary, path)


def flatten_call(metadata):
    return metadata.get("stages") or [metadata]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--resume", action="store_true")
    args = parser.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    corpus = json.loads((ROOT / "official-input.json").read_text(encoding="utf-8"))
    if len(corpus["turns"]) != 28:
        raise SystemExit("Expected exactly 28 official input turns.")
    protocol_path = ROOT / "common-protocol.txt"
    model.PROTOCOL = protocol_path.read_text(encoding="utf-8")
    variants = {
        "gemini_delivery_v14": ROOT / "rules" / "gemini-delivery-v1.4.md",
        "shouyi_v24": ROOT / "rules" / "shouyi-v2.4.md",
    }
    secret = getpass.getpass("DeepSeek API key (hidden): ")
    clients, runs, workspaces = {}, {}, {}
    for name, rule_path in variants.items():
        output = ROOT / (name + ".json")
        text = rule_path.read_text(encoding="utf-8")
        client = model.ModelClient(text)
        client.configure({"base_url": "https://api.deepseek.com", "model": "deepseek-flash", "api_key": secret})
        clients[name] = client
        identity = {
            "rules_sha256": sha256(rule_path), "protocol_sha256": sha256(protocol_path),
            "official_input_sha256": sha256(ROOT / "official-input.json"),
            "source_sha256": {n: sha256(ROOT / "frozen-source" / n) for n in ("engine.py", "model.py")},
        }
        if output.exists():
            if not args.resume:
                raise SystemExit("Existing output preserved; use --resume to continue explicitly.")
            run = json.loads(output.read_text(encoding="utf-8"))
            if any(run.get(k) != v for k, v in identity.items()):
                raise SystemExit("Cannot resume with changed inputs or code.")
            ws = engine.Workspace(**run["workspace"])
            run["status"] = "completed" if len(ws.turns) == 28 else "running"
        else:
            ws = engine.Workspace("rules-comparison", "Official 28")
            run = {
                "variant": name, "status": "running", "started_at": timestamp(),
                "rules_file": rule_path.relative_to(ROOT).as_posix(), "rules_characters": len(text),
                "rules_title": next(line for line in text.splitlines() if line.strip()),
                "interface": "common-protocol.txt; original app source frozen; only runtime PROTOCOL overridden",
                "model": client.public(), "thinking": "disabled", "temperature": 0,
                "context_policy": "live memory + last 8 turns; owner only",
                "network_retry_limit": 0, "format_repair_limit": 1,
                "planned_turns": 28, "attempts": [], "workspace": ws.public(), **identity,
            }
        runs[name], workspaces[name] = run, ws
    secret = ""

    def save(name):
        run, ws = runs[name], workspaces[name]
        calls = [call for attempt in run["attempts"] for call in attempt["calls"]]
        run.update(workspace=ws.public(), saved_turns=len(ws.turns), api_requests=len(calls),
                   provider_request_ids=len({c.get("request_id") for c in calls if c.get("request_id")}),
                   failed_attempts=sum(a["status"] == "failed" for a in run["attempts"]),
                   known_usage={k: sum(c.get("usage", {}).get(k, 0) for c in calls)
                                for k in ("prompt_tokens", "completion_tokens", "total_tokens")},
                   usage_missing_calls=sum(not c.get("usage") for c in calls))
        atomic_json(ROOT / (name + ".json"), run)

    for name in variants:
        save(name)
    # Interleave the two isolated conversations, rather than sharing memories.
    for index in range(28):
        for name in variants:
            run, ws, client = runs[name], workspaces[name], clients[name]
            if run["status"] == "failed" or len(ws.turns) > index:
                continue
            item = corpus["turns"][index]
            attempt = {"turn": index + 1, "started_at": timestamp()}
            try:
                entry = engine.process(ws, item["text"], item["role"], model=client.decide)
                attempt.update(status="saved", calls=flatten_call(entry["model_call"]))
                run["status"] = "completed" if len(ws.turns) == 28 else "running"
                if len(ws.turns) == 28:
                    run["finished_at"] = timestamp()
                    (ROOT / (name + "-memory-LIMING.md")).write_text(engine.export_markdown(ws), encoding="utf-8")
            except (model.ModelError, ValueError) as error:
                attempt.update(status="failed", error=str(error), calls=getattr(error, "calls", []))
                run.update(status="failed", stopped_at=timestamp())
            run["attempts"].append(attempt)
            save(name)
            print(f"{name}: {len(ws.turns)}/28 saved; calls={run['api_requests']}; status={run['status']}", flush=True)
            if attempt["status"] == "failed":
                print(attempt["error"], flush=True)
    for name, run in runs.items():
        print(json.dumps({k: run[k] for k in ("variant", "status", "saved_turns", "api_requests", "known_usage")}), flush=True)


if __name__ == "__main__":
    main()
